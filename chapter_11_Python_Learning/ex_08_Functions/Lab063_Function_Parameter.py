# This program shows a function that takes parameters (input values).
# Type 2 - No return type and with parameters. 



# Here "name" is a parameter: a value the function expects to receive.
def greet(name): # param
    print("Hi,", name)


# Each call passes a different argument (the actual value given to the function).
greet("Pramod") # argument
greet("Amit")
greet(34.56)

# This program demonstrates the built-in functions max() and min().
# max() returns the largest number; min() returns the smallest.
result = max(3, 4, 5, 100, 101)
print(result)


# min() returns the smallest number from the values given.
result_min = min(3, 4)
print(result_min)


# max() works with any number of values.
result = max(3, 4, 67, -1, 190, 999, 100000, 9899, -1)
print(result)

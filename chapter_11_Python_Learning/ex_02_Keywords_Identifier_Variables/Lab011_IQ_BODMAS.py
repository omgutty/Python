# This program demonstrates operator precedence (BODMAS).
# Multiplication (*) happens BEFORE addition and subtraction.
a = 10 + 34 * 3 - 1
# So the maths is: 10 + (34 * 3) - 1 = 10 + 102 - 1 = 111.
print(a)

# BODMAS
#
# BODMAS is an acronym that helps remember the order of operations in mathematics:
# B: Brackets
# O: Order of powers or roots
# D: Division
# M: Multiplication
# A: Addition
# S: Subtraction

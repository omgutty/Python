# This program demonstrates DYNAMIC TYPING.
# The same variable can hold different types, one after another.

# Dynamically typed

# age first holds an integer (a whole number).
age = 98
print(type(age))
# Now the same variable holds a string (text).
age = "Pramod"
print(type(age))
# And now it holds a boolean (True or False).
age = True
print(type(age))

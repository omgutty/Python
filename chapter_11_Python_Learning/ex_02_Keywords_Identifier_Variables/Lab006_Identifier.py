# This program demonstrates IDENTIFIERS - the names we give to variables.
# An identifier can start with a letter or an underscore (_).
age = 65
_age = 65
print(age)
print(_age)


# _ is a valid identifier too - it is often used for throwaway values.
_ = 12
print(_)
_ = _ + 1
print(_)

# 123abc = 90
# Identifiers can contain numbers, but cannot START with a number.
abc123 = "abc123"
print(abc123)



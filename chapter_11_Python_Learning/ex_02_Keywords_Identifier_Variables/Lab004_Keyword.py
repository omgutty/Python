# This program demonstrates KEYWORDS - reserved words in Python.
# Keywords have special meanings, so they cannot be used as variable names.
# print()
# class
# None
# break

# import loads a ready-made module called keyword.
import keyword

# The keyword module has a list of all Python keywords.
print(keyword.kwlist)


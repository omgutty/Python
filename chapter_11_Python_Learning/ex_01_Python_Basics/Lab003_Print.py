# This program demonstrates extra options of print(): sep and end.
# sep changes the separator between values; end changes what comes after.
print("Hello", "World")
# sep="*" puts a * between the values; end="\t" ends the line with a tab.
print("Hello", "World", "TheTestingAcademy", sep="*", end="\t")
print("Hello", "World", sep="-")

print("*", "*", sep="-")

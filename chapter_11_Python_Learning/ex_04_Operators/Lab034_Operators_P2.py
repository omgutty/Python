# This program shows the power operator **.
# ** raises a number to a power, for example 2 ** 3 means 2 x 2 x 2.

# 2 to the power 2 = 2 x 2 = 4
print(2 ** 2)  # ** - power
# 2 to the power 3 = 2 x 2 x 2 = 8
print(2 ** 3)  # ** - power
# 2 to the power 4 = 2 x 2 x 2 x 2 = 16
print(2 ** 4)  # ** - power
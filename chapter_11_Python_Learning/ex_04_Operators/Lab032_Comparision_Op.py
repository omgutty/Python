# This program demonstrates comparison operators.
# Comparison operators compare two values and give True or False.

# Put 10 into x and 20 into y in one line.
x, y = 10, 20
# == checks if two values are equal.
print(x == y)  # False
# != checks if two values are NOT equal.
print(x != y)  # True
# > checks if the left side is greater than the right side.
print(x > y)   # False
# < checks if the left side is smaller than the right side.
print(x < y)   # True
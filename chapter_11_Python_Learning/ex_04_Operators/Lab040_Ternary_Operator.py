# This program shows the ternary operator: a short if-else in one line.
# Format:  value_if_true  if  condition  else  value_if_false
# Ternary Operator:  if-else statement.

# Two numbers to compare.
x = 10
y = 20

# If x > y is True print the first text, otherwise print the second text.
print("x is grater than y" if x > y else "x is less than y")


# This program shows the difference between // and /.
# // gives the whole number part (quotient), / always gives a float.

# 5 // 2 = 2 (the whole number part, the remainder is thrown away)
print(5//2) # Q (int)
# 5 / 2 = 2.5 (normal division always gives a float)
print(5/2) # Div (always give you float)
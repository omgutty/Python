# This program practises the print() function.
# print() shows text or values on the screen.
print("Om Namassivaya gutty");

# print() can show several values at once, separated by a space.
print("om",0o007,"Team lead QA", True);

print(3);

print(3+3);  # Python can do the maths first, then print the answer (6)
# comment
print(3,4,5,)


# sep and end are extra options (arguments) of print()
# sep: what goes BETWEEN the values, end: what goes AFTER the last value
print("om", "gutty", sep='$$', end="^^")
# only once we can use sep and end for single statment 
# sep will be separated with defined string between the mentioned string
print(123,567, sep=000,end=000);



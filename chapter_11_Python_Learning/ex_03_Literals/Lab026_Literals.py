# This program demonstrates different kinds of literals.
# A literal is a value written directly in the code (numbers, text, etc.).
# decimal system ->  base  -> 10
age = 89

# binary - base system ->  2
# 0b1010 is binary (base 2) - it equals 10 in normal decimal.
binary_number = 0b1010 # -> # 10 decimal system

# Octal  -> base 8
# 0o130 is octal (base 8) - the 0o prefix means octal.
o = 0o130

# Hex  -> base 16
# 0x12c is hexadecimal (base 16) - the 0x prefix means hex.
d = 0x12c

pi = 3.14  # float

# String , str
# A string literal is text written inside quotes.
name = "Pramod"

# A boolean literal is either True or False.
is_pramod_married = True  # bool

# complex
# A complex number literal has a real part and an imaginary part (j).
complex_number = 1 + 7j
# This program demonstrates data types and two built-in functions.
# type() tells us the data type of a value.
gst = 18.45
# 18.45 has a decimal point, so it is a float.
print(type(gst))


# max() returns the biggest value; min() returns the smallest.
result = max(45, 65)
result_min = min(45, 65)
print(result)
print(result_min)

# This program shows two while loops.
# A while loop repeats as long as its condition is True.

# Start count at 0.
count = 0
# Keep looping while count is smaller than 5.
while count < 5:
    # Print the current value of count.
    print("Count is:", count)
    # Increase count by 1, otherwise the loop would never stop.
    count += 1

# Another while loop, this time for running test cases.
test_id = 0
# Loop while test_id is smaller than 10 (so 0 to 9 = 10 runs).
while test_id < 10:
    print("Running the testcase -> ",test_id)
    # Add 1 to test_id each round.
    test_id = test_id + 1
# This program shows a for loop with the range() function.
# range(start, stop, step) gives numbers from start up to (but not including) stop.
# Loop
# range - range( start, stop-1, step)
# Repeat a block of code

# range(1, 10, 1) gives 1, 2, 3, ..., 9 (10 is NOT included).
for i in range(1,10,1):
    # Print the current number on each round of the loop.
    print(i)

